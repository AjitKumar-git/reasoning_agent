                "    tract_acc = tract_acc.at[:, dst, :].add(tracts_out)\n",
                "    rad_in = jnp.matmul(state, params[\"core.radial_proj_in.weight\"].T)\n",
                "    reentrant = jnp.einsum('bki,kjio->bjo', rad_in, params[\"core.reentrant_field\"])\n",
